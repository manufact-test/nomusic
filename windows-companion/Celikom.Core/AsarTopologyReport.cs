namespace Celikom.Companion.Core;

public sealed record AsarTopologyReport(
    string State,
    string OwnerHashMatch,
    int TotalPackagedJsFiles,
    int InspectedJsFiles,
    int PackagedHtmlFiles,
    int PackagedPreloadJsFiles,
    bool HasUnpackedDirectory,
    bool HasBrowserWindowMarker,
    bool HasLoadUrlMarker,
    bool HasLoadFileMarker,
    bool HasPreloadMarker,
    bool HasYandexMusicHostMarker,
    bool HasYandexStaticHostMarker,
    bool HasLocalRendererMarker,
    bool HasFileInfoMarker,
    bool HasFileInfoBatchMarker,
    bool HasWebpackMarker,
    bool HasAutoUpdaterMarker,
    bool InspectionIncomplete)
{
    public string SafeReport() => string.Join(Environment.NewLine,
        "W2: packaged Electron boot / renderer topology (read-only)",
        $"Topology state: {State}",
        $"Owner W1 archive identity: {OwnerHashMatch}",
        $"Packaged JavaScript files: {TotalPackagedJsFiles}",
        $"Inspected JavaScript files: {InspectedJsFiles}",
        $"Packaged HTML files: {PackagedHtmlFiles}",
        $"Preload-named JavaScript files: {PackagedPreloadJsFiles}",
        $"app.asar.unpacked directory present: {HasUnpackedDirectory}",
        $"BrowserWindow hint: {HasBrowserWindowMarker}",
        $"loadURL hint: {HasLoadUrlMarker}",
        $"loadFile hint: {HasLoadFileMarker}",
        $"preload binding hint: {HasPreloadMarker}",
        $"Yandex Music host string hint: {HasYandexMusicHostMarker}",
        $"Yandex static assets string hint: {HasYandexStaticHostMarker}",
        $"Local renderer string hint: {HasLocalRendererMarker}",
        $"getFileInfo string hint: {HasFileInfoMarker}",
        $"Batch file-info string hint: {HasFileInfoBatchMarker}",
        $"Webpack string hint: {HasWebpackMarker}",
        $"Updater string hint: {HasAutoUpdaterMarker}",
        $"Packaged-code inspection incomplete: {InspectionIncomplete}",
        "IMPORTANT: hints are not proof of an actual runtime audio hook.",
        "No scripts, domains, absolute paths, cookies, tokens or account data are exported.",
        "All Yandex application files remain unchanged.");
}
